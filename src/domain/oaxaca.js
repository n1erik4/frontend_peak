/** Ventana visible del mapa: cuadrada y centrada en el estado. */
const VISTA = { lonMin: -98.95, lonMax: -93.45, latMin: 14.4, latMax: 19.9 };

/** Proyección equirectangular a un viewBox de 0–100. */
export function aVista(lon, lat) {
  const x = ((lon - VISTA.lonMin) / (VISTA.lonMax - VISTA.lonMin)) * 100;
  const y = ((VISTA.latMax - lat) / (VISTA.latMax - VISTA.latMin)) * 100;
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
}

export function trazoContorno() {
  return CONTORNO_OAXACA.map(([lon, lat], i) => `${i ? "L" : "M"}${aVista(lon, lat).join(" ")}`).join(" ") + " Z";
}

export function rectVista([lonMin, latMin, lonMax, latMax]) {
  const [x1, y1] = aVista(lonMin, latMax);
  const [x2, y2] = aVista(lonMax, latMin);
  return { x: x1, y: y1, w: x2 - x1, h: y2 - y1 };
}

/** oeste: letra para el oeste según el idioma ("O" en español, "W" en inglés). */
export const formatearCoord = (lat, lon, oeste = "O") =>
  `${Math.abs(lat).toFixed(2)}° ${lat >= 0 ? "N" : "S"} · ${Math.abs(lon).toFixed(2)}° ${lon >= 0 ? "E" : oeste}`;
